const FALLBACK_ACTIVITIES = {
  "morning": ["🌅 Sunrise trek...", "🚲 Guided historical bicycle tour...", "☕ Traditional breakfast crawl..."],
  "afternoon": ["🎨 Immersive hands-on artisan masterclass...", "🍲 Gastronomic culinary food tour...", "🏛️ Deep-dive exploration..."],
  "evening": ["🌇 Panoramic sunset viewing...", "🏮 Vibrant night market exploration...", "🛶 Relaxing twilight cruise..."]
};

export function generateItinerary(destination, places, days) {
  const regionKey =
    places.length > 0
      ? places[0].trim().toLowerCase()
      : "";

  const pool = globalCountriesDB[regionKey] || {};

  const structuredDays = Array.from({ length: days }, (_, index) => {
    const day = index + 1;

    const dayData =
      pool[`day${Math.min(day, 3)}`] || FALLBACK_ACTIVITIES;

    return {
      dayNumber: day,
      title: `Day ${day}`,

      options: {
        morning: dayData.morning,
        afternoon: dayData.afternoon,
        evening: dayData.evening,
      },
    };
  });

  return {
    status: "success",
    region_focused: regionKey || destination,
    days_data: structuredDays,
  };
}